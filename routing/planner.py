"""
planner.py

Graph search algorithms for the TwinRoute-M routing engine.

This module provides graph-based route planning algorithms that operate
on the NavigationGraph generated by GraphBuilder.

Currently Supported
-------------------
- Dijkstra's Shortest Path
- A* Search

Future Extensions
-----------------
- K-Shortest Paths
- Multi-objective Routing
- Dynamic Replanning
- Time-dependent Routing
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import List

from .graph import NavigationGraph

import heapq
import math
import time

# ==============================================================
# Search Algorithms
# ==============================================================

class SearchAlgorithm(Enum):
    """
    Supported graph search algorithms.
    """

    DIJKSTRA = "dijkstra"
    ASTAR = "astar"


# ==============================================================
# Search Statistics
# ==============================================================

@dataclass(slots=True)
class SearchStatistics:
    """
    Performance statistics collected during graph search.

    Parameters
    ----------
    expanded_nodes
        Number of graph nodes expanded.

    explored_edges
        Number of graph edges examined.

    execution_time
        Search execution time in seconds.

    total_cost
        Total path cost.

    total_distance
        Total sailing distance (km).
    """

    expanded_nodes: int = 0
    explored_edges: int = 0

    execution_time: float = 0.0

    total_cost: float = 0.0
    total_distance: float = 0.0


# ==============================================================
# Search Result
# ==============================================================

@dataclass(slots=True)
class SearchResult:
    """
    Result returned by a routing algorithm.

    Parameters
    ----------
    path
        Ordered list of graph node IDs.

    statistics
        Search performance statistics.

    algorithm
        Algorithm used to generate the path.
    """

    path: List[int] = field(default_factory=list)

    statistics: SearchStatistics = field(
        default_factory=SearchStatistics
    )

    algorithm: SearchAlgorithm = SearchAlgorithm.DIJKSTRA


# ==============================================================
# Graph Planner
# ==============================================================

class GraphPlanner:
    """
    Graph-based route planner.

    Parameters
    ----------
    graph
        Navigation graph used for path planning.
    """

    def __init__(
        self,
        graph: NavigationGraph,
    ) -> None:

        self.graph = graph
        
    # ---------------------------------------------------------
    # Graph Access Methods
    # ---------------------------------------------------------

    def get_node(
        self,
        node_id: int,
    ):
        """
        Return a graph node.

        Parameters
        ----------
        node_id
            Graph node identifier.

        Returns
        -------
        GraphNode
            Requested graph node.
        """

        return self.graph.get_node(node_id)

    # ---------------------------------------------------------

    def neighbors(
        self,
        node_id: int,
    ) -> set[int]:
        """
        Return neighbouring node IDs.

        Parameters
        ----------
        node_id
            Graph node identifier.

        Returns
        -------
        set[int]
            IDs of adjacent nodes.
        """

        return self.graph.neighbors(node_id)

    # ---------------------------------------------------------

    def get_edge(
        self,
        source: int,
        target: int,
    ):
        """
        Return the edge connecting two nodes.

        Parameters
        ----------
        source
            Source node ID.

        target
            Target node ID.

        Returns
        -------
        GraphEdge
            Directed edge.
        """

        return self.graph.get_edge(source, target)

    # ---------------------------------------------------------

    def edge_cost(
        self,
        source: int,
        target: int,
    ) -> float:
        """
        Return the traversal cost of an edge.

        Parameters
        ----------
        source
            Source node.

        target
            Target node.

        Returns
        -------
        float
            Total edge traversal cost.
        """

        edge = self.get_edge(source, target)

        return edge.cost.total_cost

    # ---------------------------------------------------------

    def edge_distance(
        self,
        source: int,
        target: int,
    ) -> float:
        """
        Return the geometric distance of an edge.

        Parameters
        ----------
        source
            Source node.

        target
            Target node.

        Returns
        -------
        float
            Edge distance in kilometres.
        """

        edge = self.get_edge(source, target)

        return edge.cost.distance
    
    # ---------------------------------------------------------
    # Path Utilities
    # ---------------------------------------------------------

    def reconstruct_path(
        self,
        previous: dict[int, int],
        start: int,
        goal: int,
    ) -> List[int]:
        """
        Reconstruct a path from predecessor links.

        Parameters
        ----------
        previous
            Mapping from node ID to its predecessor.

        start
            Starting node ID.

        goal
            Goal node ID.

        Returns
        -------
        list[int]
            Ordered list of node IDs from start to goal.

        Raises
        ------
        ValueError
            If no valid path exists.
        """

        if start == goal:
            return [start]

        if goal not in previous:
            raise ValueError(
                "No path exists between the specified nodes."
            )

        path: List[int] = []

        current = goal

        while current != start:

            path.append(current)

            current = previous[current]

        path.append(start)

        path.reverse()

        return path

    # ---------------------------------------------------------

    def compute_path_cost(
        self,
        path: List[int],
    ) -> float:
        """
        Compute the total traversal cost of a path.

        Parameters
        ----------
        path
            Ordered node IDs.

        Returns
        -------
        float
            Total accumulated edge cost.
        """

        if len(path) < 2:
            return 0.0

        total = 0.0

        for source, target in zip(path[:-1], path[1:]):

            total += self.edge_cost(source, target)

        return total

    # ---------------------------------------------------------

    def compute_total_distance(
        self,
        path: List[int],
    ) -> float:
        """
        Compute the sailing distance of a path.

        Parameters
        ----------
        path
            Ordered node IDs.

        Returns
        -------
        float
            Total great-circle distance in kilometres.
        """

        if len(path) < 2:
            return 0.0

        distance = 0.0

        for source, target in zip(path[:-1], path[1:]):

            distance += self.edge_distance(source, target)

        return distance
    
    # ---------------------------------------------------------
    # Heuristic
    # ---------------------------------------------------------

    def heuristic(
        self,
        node_id: int,
        goal_id: int,
    ) -> float:
        """
        Estimate the remaining cost between two graph nodes.

        The heuristic is the straight-line (great-circle)
        distance between the current node and the goal.

        Parameters
        ----------
        node_id
            Current graph node.

        goal_id
            Destination graph node.

        Returns
        -------
        float
            Estimated remaining cost (km).
        """

        current = self.get_node(node_id)

        goal = self.get_node(goal_id)

        lat1, lon1 = current.coordinate
        lat2, lon2 = goal.coordinate

        return self._haversine_distance(
            lat1,
            lon1,
            lat2,
            lon2,
        )
        
    # ---------------------------------------------------------

    @staticmethod
    def _haversine_distance(
        lat1: float,
        lon1: float,
        lat2: float,
        lon2: float,
    ) -> float:
        """
        Great-circle distance between two coordinates.

        Returns
        -------
        float
            Distance in kilometres.
        """

        from math import radians, sin, cos, sqrt, atan2

        R = 6371.0

        lat1 = radians(lat1)
        lon1 = radians(lon1)

        lat2 = radians(lat2)
        lon2 = radians(lon2)

        dlat = lat2 - lat1
        dlon = lon2 - lon1

        a = (
            sin(dlat / 2) ** 2
            + cos(lat1)
            * cos(lat2)
            * sin(dlon / 2) ** 2
        )

        c = 2 * atan2(
            sqrt(a),
            sqrt(1 - a),
        )

        return R * c
    
    # ---------------------------------------------------------
    # Dijkstra Search
    # ---------------------------------------------------------

    def dijkstra(
        self,
        start: int,
        goal: int,
    ) -> SearchResult:
        """
        Compute the shortest path using Dijkstra's algorithm.

        Parameters
        ----------
        start
            Source node ID.

        goal
            Destination node ID.

        Returns
        -------
        SearchResult
            Shortest path and search statistics.
        """

        start_time = time.perf_counter()

        # --------------------------------------------------
        # Priority queue
        # --------------------------------------------------

        frontier: list[tuple[float, int]] = []

        heapq.heappush(frontier, (0.0, start))

        # --------------------------------------------------
        # Search state
        # --------------------------------------------------

        distance: dict[int, float] = {
            start: 0.0
        }

        previous: dict[int, int] = {}

        visited: set[int] = set()

        statistics = SearchStatistics()

        # --------------------------------------------------
        # Main search loop
        # --------------------------------------------------

        while frontier:

            current_cost, current = heapq.heappop(frontier)

            if current in visited:
                continue

            visited.add(current)

            statistics.expanded_nodes += 1

            if current == goal:
                break

            for neighbor in self.neighbors(current):

                statistics.explored_edges += 1

                edge_cost = self.edge_cost(
                    current,
                    neighbor,
                )

                new_cost = current_cost + edge_cost

                if new_cost < distance.get(
                    neighbor,
                    math.inf,
                ):

                    distance[neighbor] = new_cost

                    previous[neighbor] = current

                    heapq.heappush(
                        frontier,
                        (
                            new_cost,
                            neighbor,
                        ),
                    )

        # --------------------------------------------------
        # Build final path
        # --------------------------------------------------

        path = self.reconstruct_path(
            previous,
            start,
            goal,
        )

        statistics.execution_time = (
            time.perf_counter() - start_time
        )

        statistics.total_cost = self.compute_path_cost(
            path,
        )

        statistics.total_distance = (
            self.compute_total_distance(path)
        )

        return SearchResult(
            path=path,
            statistics=statistics,
            algorithm=SearchAlgorithm.DIJKSTRA,
        )
        
    # ---------------------------------------------------------
    # A* Search
    # ---------------------------------------------------------

    def astar(
        self,
        start: int,
        goal: int,
    ) -> SearchResult:
        """
        Compute the shortest path using the A* search algorithm.

        Parameters
        ----------
        start
            Source node ID.

        goal
            Destination node ID.

        Returns
        -------
        SearchResult
            Shortest path and search statistics.
        """

        start_time = time.perf_counter()

        # --------------------------------------------------
        # Priority Queue
        # --------------------------------------------------

        frontier: list[tuple[float, int]] = []

        heapq.heappush(frontier, (0.0, start))

        # --------------------------------------------------
        # Search State
        # --------------------------------------------------

        g_cost: dict[int, float] = {
            start: 0.0
        }

        previous: dict[int, int] = {}

        visited: set[int] = set()

        statistics = SearchStatistics()

        # --------------------------------------------------
        # Main Loop
        # --------------------------------------------------

        while frontier:

            _, current = heapq.heappop(frontier)

            if current in visited:
                continue

            visited.add(current)

            statistics.expanded_nodes += 1

            if current == goal:
                break

            for neighbor in self.neighbors(current):

                statistics.explored_edges += 1

                edge_cost = self.edge_cost(
                    current,
                    neighbor,
                )

                tentative_g = (
                    g_cost[current]
                    + edge_cost
                )

                if tentative_g < g_cost.get(
                    neighbor,
                    math.inf,
                ):

                    g_cost[neighbor] = tentative_g

                    previous[neighbor] = current

                    f_cost = (
                        tentative_g
                        + self.heuristic(
                            neighbor,
                            goal,
                        )
                    )

                    heapq.heappush(
                        frontier,
                        (
                            f_cost,
                            neighbor,
                        ),
                    )

        # --------------------------------------------------
        # Build Result
        # --------------------------------------------------

        path = self.reconstruct_path(
            previous,
            start,
            goal,
        )

        statistics.execution_time = (
            time.perf_counter()
            - start_time
        )

        statistics.total_cost = (
            self.compute_path_cost(path)
        )

        statistics.total_distance = (
            self.compute_total_distance(path)
        )

        return SearchResult(
            path=path,
            statistics=statistics,
            algorithm=SearchAlgorithm.ASTAR,
        )